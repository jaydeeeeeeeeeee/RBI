// ── Helper: write config.php ──────────────────────────────────────────────────
function writeConfig(array $d): bool {
    $blotter_signer = addslashes($d['signer_name'] ?? '');
    $ts = time();
    $content = <<<PHP
<?php
/**
 * ProjectRBI – Master Configuration
 * Generated by setup wizard on {$ts}.
 */

// ── Block direct browser access ───────────────────────────────────────────────
if (basename(\$_SERVER['SCRIPT_FILENAME'] ?? '') === 'config.php') {
    http_response_code(403); exit('Access denied.');
}

// ── Barangay Identity ─────────────────────────────────────────────────────────
define('BRGY_NUMBER',   '{$d['brgy_number']}');
define('BRGY_NAME',     '{$d['brgy_name']}');
define('BRGY_ZONE',     '{$d['brgy_zone']}');
define('BRGY_FULLNAME', '{$d['brgy_name']} {$d['brgy_zone']}');
define('BRGY_CITY',     '{$d['brgy_city']}');
define('BRGY_DISTRICT', '{$d['brgy_district']}');
define('BRGY_PROVINCE', '{$d['brgy_province']}');

// ── Map Coordinates ───────────────────────────────────────────────────────────
define('BRGY_LAT', {$d['brgy_lat']});
define('BRGY_LNG', {$d['brgy_lng']});

// ── E-Blotter ─────────────────────────────────────────────────────────────────
