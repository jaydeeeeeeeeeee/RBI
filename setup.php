// ── Helper: test DB connection ────────────────────────────────────────────────
function testDb(string $host, int $port, string $user, string $pass, string $name = ''): array {
    $conn = @new mysqli($host, $user, $pass, '', $port);
    if ($conn->connect_error) return ['ok' => false, 'msg' => $conn->connect_error];
    if ($name) {
        if (!$conn->select_db($name)) {
            // Try to create it
            if (!$conn->query("CREATE DATABASE IF NOT EXISTS `$name` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"))
                return ['ok' => false, 'msg' => 'Cannot create database: ' . $conn->error];
        }
    }
    return ['ok' => true, 'conn' => $conn];
}

